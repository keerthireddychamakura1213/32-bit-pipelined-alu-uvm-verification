        default: clz_count = 6'd32;
    endcase
end

//==============================================================================
// Operation Logic
//==============================================================================
always_comb begin
    case (op_sel)
        2'b00: begin // MIN - Minimum (Signed)
            result = (signed_a < signed_b) ? operand_a : operand_b;
        end

        2'b01: begin // MAX - Maximum (Signed)
            result = (signed_a > signed_b) ? operand_a : operand_b;
        end

        2'b10: begin // ABS - Absolute Value
            if (operand_a[DATA_WIDTH-1]) begin
                // Negative: negate (two's complement)
                result = (~operand_a) + 1'b1;
            end else begin
                // Positive or zero: keep as is
                result = operand_a;
            end
        end

        2'b11: begin // CLZ - Count Leading Zeros
            result = {{(DATA_WIDTH-6){1'b0}}, clz_count};
        end

        default: result = '0;
    endcase
end

endmodule : special_unit
